import { chromium } from '@playwright/test';
const [S, zip, name] = process.argv.slice(2);
const b = await chromium.launch({ args: ['--enable-gpu', '--use-angle=gl'] });
const p = await b.newPage({ viewport: { width: 1280, height: 760 } });
p.on('console', (m) => m.type() === 'error' && console.log('console: ' + m.text().slice(0, 200)));
p.on('pageerror', (e) => console.log('pageerror: ' + e.message.slice(0, 300)));
await p.goto('http://localhost:4173/#v=galaxy');
await p.getByTestId('zip-input').setInputFiles(zip);
await p.waitForSelector('[data-view="galaxy"][data-layout="settled"]', { timeout: 60000 });
await p.waitForTimeout(800);
await p.screenshot({ path: `${S}/${name}.png` });
const fps = await p.evaluate(() => new Promise((res) => { const f = []; const t = (x) => { f.push(x); if (x - f[0] < 2000) requestAnimationFrame(t); else res(((f.length - 1) * 1000) / (x - f[0])); }; requestAnimationFrame(t); }));
console.log(name, 'idle fps', Math.round(fps));
await b.close();
